data class OnboardingData(
    val imageRes: Int,
    val titlePart1: String,
    val titlePart2: String,
    val description: String
)

@Composable
fun OnboardingScreen(onFinish: () -> Unit, isPremium: Boolean = false, adsState: AdsState? = null) {
    val onboardingItems = listOf(
        OnboardingData(
            R.drawable.intro_1,
            "Welcome To Live",
            "cricScore",
            "Stay in the game with our real-time cricket score app. Get up to the minute updates on matches from ground the world."
        ),
        OnboardingData(
            R.drawable.intro_2,
            "Explore The",
            "World of Cricket",
            "Dive into the thrilling world of cricket with our app! we’re here to make your cricket experience unforgettable."
        ),
        OnboardingData(
            R.drawable.intro_3,
            "AI Match",
            "Prediction",
            "Get deep insights and tactical summaries generated by AI to stay ahead of the game with win probability."
        )
    )

    val pagerState = rememberPagerState(pageCount = { onboardingItems.size })
    val scope = rememberCoroutineScope()

    val radialGradient = Brush.radialGradient(
        colors = listOf(RadialTeal.copy(alpha = 0.5f), Color.Transparent),
        center = androidx.compose.ui.geometry.Offset(540f, -50f),
        radius = 1000f
    )

    val goldGradient = Brush.radialGradient(
        colors = listOf(
            RadialGold.copy(alpha = 0.25f),
            Color.Transparent
        ),
        center = Offset(540f, -50f),
        radius = 1000f
    )

    Box(
        modifier = Modifier
            .fillMaxSize()
            .background(DarkBackground)
    ) {
        // Background Radial Glow
        Box(
            modifier = Modifier
                .fillMaxWidth()
                .height(400.dp)
                .background(if (isPremium) goldGradient else radialGradient)
        )

        Column(modifier = Modifier.fillMaxSize()) {
            HorizontalPager(
                state = pagerState,
                modifier = Modifier
                    .fillMaxWidth()
                    .weight(1f)
            ) { page ->
                OnboardingPage(onboardingItems[page], page, isPremium, adsState)
            }

            // Bottom section
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(bottom = 16.dp, start = 32.dp, end = 32.dp),
                horizontalAlignment = Alignment.CenterHorizontally
            ) {
                // Page Indicator
                Row(
                    horizontalArrangement = Arrangement.spacedBy(8.dp),
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    repeat(onboardingItems.size) { iteration ->
                        val isSelected = pagerState.currentPage == iteration
                        val color = if (isSelected) {
                            if (isPremium) Color(0xFFFFD700) else Color(0xFF00BFA5)
                        } else Color.White.copy(alpha = 0.3f)
                        val width = if (isSelected) 32.dp else 10.dp
                        Box(
                            modifier = Modifier
                                .height(6.dp)
                                .width(width)
                                .clip(CircleShape)
                                .background(color)
                        )
                    }
                }

                Spacer(modifier = Modifier.height(24.dp))

                // Next Button
                Button(
                    onClick = {
                        if (pagerState.currentPage < onboardingItems.size - 1) {
                            scope.launch {
                                pagerState.animateScrollToPage(pagerState.currentPage + 1)
                            }
                        } else {
                            onFinish()
                        }
                    },
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(60.dp)
                        .border(1.dp, Color.White.copy(alpha = 0.1f), RoundedCornerShape(30.dp)),
                    colors = ButtonDefaults.buttonColors(containerColor = Color.Black),
                    shape = RoundedCornerShape(30.dp)
                ) {
                    Text(
                        text = if (pagerState.currentPage == onboardingItems.size - 1) "GET STARTED" else "NEXT",
                        color = Color.White,
                        fontSize = 18.sp,
                        fontWeight = FontWeight.Black,
                        fontFamily = GilroyFontFamily,
                        letterSpacing = 1.sp
                    )
                }
            }
        }
    }
}

@Composable
fun OnboardingPage(data: OnboardingData, pageIndex: Int, isPremium: Boolean = false, adsState: AdsState? = null) {
    Column(
        modifier = Modifier
            .fillMaxSize()
            .padding(top = 20.dp),
        horizontalAlignment = Alignment.CenterHorizontally
    ) {
        Image(
            painter = painterResource(id = data.imageRes),
            contentDescription = null,
            modifier = Modifier
                .fillMaxWidth()
                .fillMaxHeight(0.4f)
                .padding(horizontal = 20.dp),
            contentScale = ContentScale.Fit
        )
        
        Spacer(modifier = Modifier.height(16.dp))
        
        Text(
            text = data.titlePart1,
            color = Color.White,
            fontSize = 28.sp,
            fontWeight = FontWeight.Medium,
            fontFamily = GilroyFontFamily,
            textAlign = TextAlign.Center
        )
        Text(
            text = data.titlePart2,
            color = Color.White,
            fontSize = 28.sp,
            fontWeight = FontWeight.Bold,
            fontFamily = GilroyFontFamily,
            textAlign = TextAlign.Center
        )
        
        Spacer(modifier = Modifier.height(12.dp))
        
        Text(
            text = data.description,
            color = Color.White.copy(alpha = 0.7f),
            fontSize = 14.sp,
            fontFamily = GilroyFontFamily,
            textAlign = TextAlign.Center,
            lineHeight = 20.sp,
            minLines = 3,
            maxLines = 3,
            overflow = TextOverflow.Ellipsis,
            modifier = Modifier.width(300.dp)
        )

        Spacer(modifier = Modifier.weight(1f))

        // Native Ads on Screen 1 (Index 0) and Screen 3 (Index 2)
        Box(
            modifier = Modifier
                .fillMaxWidth()
                .height(210.dp) // Fixed height to match NativeAdViewHorizontal
                .padding(horizontal = 20.dp)
                .padding(bottom = 16.dp),
            contentAlignment = Alignment.Center
        ) {
            when (pageIndex) {
                0 -> {
                    if (adsState?.native_ob_1?.enabled == true && adsState.native_ob_1.ads_unit.isNotEmpty() && !isPremium) {
                        NativeAdViewHorizontal(adUnitId = adsState.native_ob_1.ads_unit, isPremium = isPremium)
                    }
                }
                2 -> {
                    if (adsState?.native_ob_3?.enabled == true && adsState.native_ob_3.ads_unit.isNotEmpty() && !isPremium) {
                        NativeAdViewHorizontal(adUnitId = adsState.native_ob_3.ads_unit, isPremium = isPremium)
                    }
                }
            }
        }
    }
}
